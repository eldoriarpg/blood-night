/**
 * Writes the TypeScript types of what the frontend exchanges, from the two descriptions the Java side generates:
 * `src/api/generated/schema.ts` from the web backend's API description (`web/backend/src/main/resources/api/openapi.json`,
 * written by `./gradlew :web-backend:generateApiSpec`) with openapi-typescript, and `src/api/generated/payload.ts` from
 * the editor payload's JSON Schema (`src/api/generated/payload.schema.json`, written by
 * `./gradlew :core:generatePayloadSchema`) with json-schema-to-typescript.
 *
 * Every string enum of either description also becomes a constant of the same name holding its values, so a single
 * import gives the union and its values. The `api-types` linter checks that what is committed is what this writes.
 */

import {readFileSync, writeFileSync, mkdirSync} from 'fs'
import {dirname, join} from 'path'
import openapiTS, {astToString} from 'openapi-typescript'
import {compile} from 'json-schema-to-typescript'
import ts from 'typescript'
import {SRC, GREEN, RESET} from './lint-utils.mjs'

export const SPEC = new URL('../../backend/src/main/resources/api/openapi.json', import.meta.url).pathname
export const PAYLOAD_SCHEMA = join(SRC, 'api', 'generated', 'payload.schema.json')
export const API_TARGET = join(SRC, 'api', 'generated', 'schema.ts')
export const PAYLOAD_TARGET = join(SRC, 'api', 'generated', 'payload.ts')

const LICENSE = `/*
 *     SPDX-License-Identifier: AGPL-3.0-only
 *
 *     Copyright (C) RainbowDashLabs and Contributor
 */`

const SCHEMA_REFERENCE = /^components\['schemas'\]\['(.+)'\]$/

/**
 * The API types as they should stand for the committed API description.
 */
export async function renderApiTypes() {
    const spec = JSON.parse(readFileSync(SPEC, 'utf-8'))
    const ast = await openapiTS(spec, {
        rootTypes: true,
        rootTypesNoSchemaPrefix: true,
        rootTypesKeepCasing: true,
        alphabetize: true,
        silent: true,
    })
    const names = rootTypeNamesBySchema(ast)
    const constants = enumConstants(spec.components?.schemas ?? {}, schemaName => names.get(schemaName))
    const body = `${astToString(ast)}\n${constants}`.replace(/[ \t]+$/gm, '')
    return `${LICENSE}\n${banner('./gradlew :web-backend:generateApiSpec')}${ending(body)}`
}

/**
 * The payload types as they should stand for the committed payload schema.
 */
export async function renderPayloadTypes() {
    const schema = JSON.parse(readFileSync(PAYLOAD_SCHEMA, 'utf-8'))
    const types = await compile(schema, 'EditorPayload', {
        bannerComment: '',
        additionalProperties: false,
        unreachableDefinitions: true,
        format: true,
        style: {singleQuote: true},
    })
    const constants = enumConstants(schema.$defs ?? {}, name => name)
    const body = `${types}\n${constants}`.replace(/[ \t]+$/gm, '')
    return `${LICENSE}\n${banner('./gradlew :core:generatePayloadSchema')}${ending(body)}`
}

function banner(command) {
    return `/**
 * Generated by \`node scripts/generate-api-types.mjs\` from what \`${command}\` writes. Do not edit: a type changes
 * when the class it describes changes.
 */
`
}

function ending(text) {
    return text.endsWith('\n') ? text : `${text}\n`
}

function rootTypeNamesBySchema(ast) {
    const names = new Map()
    for (const node of ast) {
        if (!ts.isTypeAliasDeclaration(node) || !ts.isTypeReferenceNode(node.type)) continue
        if (!ts.isIdentifier(node.type.typeName)) continue
        const schemaName = node.type.typeName.text.match(SCHEMA_REFERENCE)?.[1]
        if (schemaName) names.set(schemaName, node.name.text)
    }
    return names
}

function enumConstants(schemas, nameOf) {
    return Object.entries(schemas)
        .filter(([, schema]) => Array.isArray(schema.enum) && schema.enum.length > 0 && schema.enum.every(value => typeof value === 'string'))
        .map(([schemaName, schema]) => ({name: nameOf(schemaName), values: schema.enum}))
        .filter(constant => constant.name)
        .sort((a, b) => compareText(a.name, b.name))
        .map(({name, values}) => renderConstant(name, values))
        .join('\n')
}

function renderConstant(name, values) {
    const entries = [...new Set(values)]
        .sort(compareText)
        .map(value => `    ${propertyKey(value)}: ${JSON.stringify(value)},`)
    return `export const ${name} = {\n${entries.join('\n')}\n} as const;\n`
}

function propertyKey(value) {
    return ts.isIdentifierText(value, ts.ScriptTarget.ESNext) ? value : JSON.stringify(value)
}

function compareText(a, b) {
    return a < b ? -1 : a > b ? 1 : 0
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
    mkdirSync(dirname(API_TARGET), {recursive: true})
    writeFileSync(API_TARGET, await renderApiTypes())
    writeFileSync(PAYLOAD_TARGET, await renderPayloadTypes())
    console.log(`${GREEN}Wrote${RESET} ${API_TARGET.replace(SRC, 'src')} and ${PAYLOAD_TARGET.replace(SRC, 'src')}`)
}
