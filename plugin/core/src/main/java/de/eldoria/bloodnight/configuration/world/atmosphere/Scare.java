/**
 * A kind of sudden fright.
 */
public enum Scare {
    /**
     * The camera flinches as if hit from behind, with a hurt sound.
     */
    FLINCH,
    /**
     * A scream somewhere behind the player.
     */
    SCREAM,
    /**
     * The elder guardian's face flashes on the screen.
     */
    GUARDIAN
}
