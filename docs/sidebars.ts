import {readdirSync} from 'node:fs'
import {fileURLToPath} from 'node:url'
import type {SidebarsConfig} from '@docusaurus/plugin-content-docs'

const sidebars: SidebarsConfig = {
  guide: [
    'intro',
    {type: 'category', label: 'Getting started', items: [{type: 'autogenerated', dirName: 'getting-started'}]},
    {type: 'category', label: 'Blood nights', items: [{type: 'autogenerated', dirName: 'nights'}]},
    {type: 'category', label: 'Mobs', items: [{type: 'autogenerated', dirName: 'mobs'}]},
    {type: 'category', label: 'Rules', items: [{type: 'autogenerated', dirName: 'rules'}]},
    {type: 'category', label: 'Web editor', items: [{type: 'autogenerated', dirName: 'editor'}]},
    'commands',
    'placeholders',
    {type: 'category', label: 'For developers', items: [{type: 'autogenerated', dirName: 'developers'}]},
  ],
  reference: [{type: 'autogenerated', dirName: 'reference'}],
}

/**
 * The pages and folders a sidebar shows: the ids it names and the folders it lists on its own.
 */
function covered(items: unknown, ids: Set<string>, folders: Set<string>): void {
  if (Array.isArray(items)) {
    for (const item of items) covered(item, ids, folders)
  } else if (typeof items === 'string') {
    ids.add(items)
  } else if (items !== null && typeof items === 'object') {
    const item = items as {type?: string, id?: string, dirName?: string, items?: unknown}
    if (item.type === 'autogenerated' && item.dirName) folders.add(item.dirName)
    if (item.type === 'doc' && item.id) ids.add(item.id)
    if (item.items) covered(item.items, ids, folders)
  }
}

/**
 * Fails the build when a page is in no sidebar, since nothing would lead to it but a link.
 */
function checkEveryPageIsListed(): void {
  const ids = new Set<string>()
  const folders = new Set<string>()
  covered(Object.values(sidebars), ids, folders)
  const root = fileURLToPath(new URL('./docs/', import.meta.url))
  const pages = readdirSync(root, {recursive: true, encoding: 'utf8'})
    .filter(path => /\.mdx?$/.test(path))
    .map(path => path.replaceAll('\\', '/').replace(/\.mdx?$/, ''))
  const missing = pages.filter(page => !ids.has(page) && ![...folders].some(folder => page.startsWith(`${folder}/`)))
  if (missing.length > 0) throw new Error(`Pages in no sidebar: ${missing.join(', ')}. Add them to docs/sidebars.ts.`)
}

checkEveryPageIsListed()

export default sidebars
